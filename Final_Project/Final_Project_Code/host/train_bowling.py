"""Fit the demo's compact classifier and power anchors from accepted bowling CSV.
No source recordings are modified. Pure standard-library training, reproducible.
"""
import argparse,csv,collections,hashlib,json,math,statistics
from pathlib import Path
CATEGORIES=['straight_slow','straight_normal','straight_fast','hook_left','hook_right']
FEATURES=['peak_accel','gyro_min_x','gyro_min_y','gyro_min_z','gyro_max_x','gyro_max_y','gyro_max_z','gyro_integral_x','gyro_integral_y','gyro_integral_z','accel_mean_x','accel_mean_y','accel_mean_z']
def extract(rows):
    rows=[r for r in rows if r['phase']=='motion']
    a=[[float(r['corrected_'+k]) for k in ['ax_mps2','ay_mps2','az_mps2']] for r in rows]
    w=[[float(r['corrected_'+k]) for k in ['gx_rads','gy_rads','gz_rads']] for r in rows]
    t=[int(r['elapsed_us'])/1e6 for r in rows]
    return [max(math.sqrt(sum(v*v for v in r)) for r in a)]+[min(r[j] for r in w) for j in range(3)]+[max(r[j] for r in w) for j in range(3)]+[sum((w[i][j]+w[i-1][j])*.5*(t[i]-t[i-1]) for i in range(1,len(t))) for j in range(3)]+[statistics.mean(r[j] for r in a) for j in range(3)]
def fit(X,y):
    scale=[max(statistics.pstdev(row[j] for row in X),1e-5) for j in range(13)]
    centers=[[statistics.mean(row[j] for row,label in zip(X,y) if label==c) for j in range(13)] for c in CATEGORIES]
    return scale,centers

def main():
    root=Path(__file__).resolve().parents[1]
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--csv',type=Path,default=root/'data/bowling.csv');args=p.parse_args()
    groups=collections.defaultdict(list)
    with args.csv.open(newline='') as f:
        for r in csv.DictReader(f): groups[r['trial_id']].append(r)
    X=[];y=[]
    for rows in groups.values():
        rows.sort(key=lambda r:int(r['elapsed_us']))
        X.append(extract(rows));y.append(rows[0]['throw_category'])
    if set(y)!=set(CATEGORIES) or min(collections.Counter(y).values())<2:raise ValueError('Need at least two accepted throws per class')
    if not all(math.isfinite(v) for row in X for v in row):raise ValueError('Nonfinite input')
    confusion={c:{d:0 for d in CATEGORIES} for c in CATEGORIES}
    for i in range(len(X)):
        s,c=fit(X[:i]+X[i+1:],y[:i]+y[i+1:])
        distances=[sum(((a-b)/z)**2 for a,b,z in zip(X[i],center,s))/13 for center in c]
        confusion[y[i]][CATEGORIES[min(range(5),key=lambda j:distances[j])]]+=1
    scale,centers=fit(X,y)
    slow=statistics.median(row[0] for row,label in zip(X,y) if label=='straight_slow')
    fast=statistics.median(row[0] for row,label in zip(X,y) if label=='straight_fast')
    def floats(v):return ', '.join(f'{x:.9e}f' for x in v)
    header='// Generated by host/train_bowling.py. Do not edit by hand.\n#ifndef BOWLING_TRAINED_H\n#define BOWLING_TRAINED_H\n'
    header+=f'#define TRAINING_TRIALS {len(X)}\n#define POWER_SLOW {slow:.9e}f\n#define POWER_FAST {fast:.9e}f\n'
    header+='static const float feature_scale[13] = {'+floats(scale)+'};\n'
    header+='static const float class_centers[5][13] = {\n'+',\n'.join('    {'+floats(c)+'}' for c in centers)+'\n};\n#endif\n'
    (root/'bowling_trained.h').write_text(header)
    correct=sum(confusion[c][c] for c in CATEGORIES)
    report=dict(source=str(args.csv.resolve()),sha256=hashlib.sha256(args.csv.read_bytes()).hexdigest(),trials=len(X),counts=dict(collections.Counter(y)),features=FEATURES,scale=scale,centers=centers,power_slow=slow,power_fast=fast,leave_one_out_correct=correct,confusion=confusion,limitations='Same-person/session exploratory validation; no measured ball speed, spin or release. Physics is an adjustable game mapping.')
    (root/'bowling_model_report.json').write_text(json.dumps(report,indent=2)+'\n')
    print(f'Fitted {len(X)} throws. LOO: {correct}/{len(X)}. Power anchors: {slow:.3f}, {fast:.3f} m/s^2.')
if __name__=='__main__':main()
